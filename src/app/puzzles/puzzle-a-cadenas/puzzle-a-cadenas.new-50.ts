import type { PuzzleACadenasEntry } from './puzzle-a-cadenas.catalog';

type Visual = string | readonly string[];

type Example = {
  code: string;
  visuals: readonly Visual[];
};

const line = (label: string, value: string, result: string): string =>
  `${label} ${value} → ${result}`;

const example = (code: string, ...visuals: Visual[]): Example => ({ code, visuals });

const diagram = (label: string, rows: readonly string[], result: string): readonly string[] => [
  `@diagram ${label}`,
  ...rows,
  `@result ${result}`,
];

const flatten = (visuals: readonly Visual[]): string[] =>
  visuals.flatMap((visual) => (typeof visual === 'string' ? [visual] : [...visual]));

const makePuzzle = (
  id: string,
  title: string,
  difficulty: string,
  instructions: string,
  examples: readonly Example[],
  targets: readonly Visual[],
  answer: string,
): PuzzleACadenasEntry => ({
  id,
  title,
  difficulty,
  instructions,
  display: [
    'Exemples',
    ...examples.flatMap((item, index) => [
      `Légende ${index + 1} · code ${item.code}`,
      ...flatten(item.visuals),
    ]),
    '',
    'À résoudre',
    ...flatten(targets),
  ].join('\n'),
  answer,
});

const pathGraph = (
  label: string,
  topLeft: number,
  topRight: number,
  middle: number,
  bottomLeft: number,
  bottomRight: number,
  result: string,
): readonly string[] =>
  diagram(
    label,
    [
      `S ──${topLeft}── A ──${topRight}── T`,
      `S ───────${middle}─────── T`,
      `S ──${bottomLeft}── B ──${bottomRight}── T`,
    ],
    result,
  );

const twoBranchGraph = (
  label: string,
  topLeft: number,
  topRight: number,
  bottomLeft: number,
  bottomRight: number,
  result: string,
): readonly string[] =>
  diagram(
    label,
    [`S ──${topLeft}── A ──${topRight}── T`, `S ──${bottomLeft}── B ──${bottomRight}── T`],
    result,
  );

const cycleGraph = (label: string, rank: number, result: string): readonly string[] => {
  const base = ['A–B', 'B–C', 'C–D', 'D–E'];
  const extra = ['A–C', 'B–D', 'C–E', 'A–D', 'B–E', 'A–E'];

  return diagram(
    label,
    ['Sommets : A  B  C  D  E', `Arêtes : ${[...base, ...extra.slice(0, rank)].join(' · ')}`],
    result,
  );
};

const bridgeGraph = (label: string, bridges: number, result: string): readonly string[] => {
  const edgesByBridgeCount: Record<number, string[]> = {
    0: ['A–B', 'B–C', 'C–D', 'D–E', 'E–A'],
    1: ['A–B', 'B–C', 'C–D', 'D–A', 'C–E'],
    2: ['A–B', 'B–C', 'C–A', 'C–D', 'D–E'],
    3: ['A–B', 'B–C', 'C–D'],
    4: ['A–B', 'B–C', 'C–D', 'D–E'],
  };

  return diagram(
    label,
    ['Sommets : A  B  C  D  E', `Arêtes : ${edgesByBridgeCount[bridges]?.join(' · ') ?? ''}`],
    result,
  );
};

const coverGraph = (label: string, cover: number, result: string): readonly string[] => {
  const edges =
    cover === 1
      ? ['A–B', 'A–C', 'A–D', 'A–E']
      : cover === 2
        ? ['A–B', 'B–C', 'C–D', 'D–A']
        : ['A–B', 'A–C', 'A–D', 'B–C', 'B–D', 'C–D'];

  return diagram(label, ['Sommets : A  B  C  D  E', `Arêtes : ${edges.join(' · ')}`], result);
};

const intervalGraph = (
  label: string,
  intervals: readonly [number, number][],
  result: string,
): readonly string[] =>
  diagram(
    label,
    intervals.map(([start, end], index) => `${index + 1} : [${start} ; ${end}]`),
    result,
  );

