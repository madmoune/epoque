import type { PuzzleACadenasEntry } from './puzzle-a-cadenas.catalog';

const makePuzzle = (
  id: string,
  title: string,
  difficulty: string,
  instructions: string,
  examples: readonly string[],
  targets: readonly string[],
  answer: string,
): PuzzleACadenasEntry => ({
  id,
  title,
  difficulty,
  instructions,
  display: ['Exemples', ...examples, '', 'À résoudre', ...targets].join('\n'),
  answer,
});

const grouped = (...values: string[]): string => values.join('  ');
const results = (...values: (string | number)[]): string => `→ ${values.join(' → ')}`;
const exampleLine = (index: number, value: string, result: string | number): string =>
  `Exemple ${index}  ${value} → ${result}`;
const targetLine = (label: string, value: string): string => `${label}  ${value} → ?`;

const numberGrid = (rows: readonly (readonly string[])[]): string => {
  const columns = rows[0]?.length ?? 0;
  const top = `┌${Array.from({ length: columns }, () => '───').join('┬')}┐`;
  const middle = `├${Array.from({ length: columns }, () => '───').join('┼')}┤`;
  const bottom = `└${Array.from({ length: columns }, () => '───').join('┴')}┘`;
  const body = rows
    .map((row, index) => `│ ${row.join(' │ ')} │${index < rows.length - 1 ? `\n${middle}` : ''}`)
    .join('\n');

  return [top, body, bottom].join('\n');
};

const numberGrids = (...grids: readonly (readonly (readonly string[])[])[]): string => {
  const rendered = grids.map((grid) => numberGrid(grid).split('\n'));

  return rendered[0]
    .map((_, rowIndex) => rendered.map((grid) => grid[rowIndex]).join('  '))
    .join('\n');
};

const cubeNet = (
  label: string,
  top: string,
  row: string,
  bottom: string,
  query: string,
  result: string,
): string => [label, top, row, bottom, `${query} → ${result}`].join('\n');

const rotation = (
  label: string,
  before: readonly string[],
  after: readonly string[],
  result: string,
): string => [label, ...before, '→', ...after, `→ ${result}`].join('\n');

